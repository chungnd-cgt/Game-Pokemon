// "Lightning Rod" -> "lightningRod"
const abilityId = (name) => name.replace(/[^A-Za-z ]/g, '').split(' ')
  .map((w, i) => (i ? w[0].toUpperCase() + w.slice(1).toLowerCase() : w.toLowerCase())).join('');

export const abilityIdOf = abilityId;

// Đặc tính thường và đặc tính ẩn của một loài (game đã có đủ mọi đặc tính của 151 loài; đặc tính lạ thì bỏ qua)
export function speciesAbilities(slug) {
  const list = DEX_BY_SLUG[slug].abilities.map((a) => ({ id: abilityId(a.name), hidden: a.hidden }))
    .filter((a) => ABILITIES[a.id]);
  return {
    normal: list.filter((a) => !a.hidden).map((a) => a.id),
    hidden: list.find((a) => a.hidden)?.id ?? null,
  };
}
